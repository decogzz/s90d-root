#!/usr/bin/env python3
"""debloat.py — the debloat list, single-sourced and generated.

Reads config/debloat.services (one service per line:
    group | unit | description)
and regenerates every consumer:

    scripts/debloat.py list [group]      — print the list (all, or one group)
    scripts/debloat.py sync              — regenerate ALL generated files
    scripts/debloat.py sync --win-config — also refresh the LIVE Windows
                                          daemon config.toml (IRREVERSIBLE
                                          edit of C:\\Users\\decog\\s90d-root\\
                                          config.toml — asks first)

Consumers regenerated by 'sync':
  - config/daemon.example.toml   (post_root_commands mask loop)
  - tools/windows/run-mask-apply.bat (standalone idempotent mask session)
  - README.md debloat table      (between <debloat-table> markers)
  - docs/journal.md count/prose sanity-checked, not overwritten

The mask command generated everywhere is identical:
    for s in <units...>; do systemctl mask --runtime --now $s; done
All masks are volatile (/run) — a TV reboot returns the TV to stock.
"""
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SERVICES = os.path.join(ROOT, 'config', 'debloat.services')
WIN_CONFIG = '/mnt/c/Users/decog/s90d-root/config.toml'

# --- the live Windows daemon config: regenerated sections ---
WIN_POST_ROOT_TMPL = """post_root_commands = [
  "for s in {units}; do systemctl mask --runtime --now $s; done",
]"""

def parse(path=SERVICES):
    out = []
    for n, raw in enumerate(open(path, encoding='utf-8'), 1):
        line = raw.strip()
        if not line or line.startswith('#'):
            continue
        parts = [p.strip() for p in line.split('|')]
        if len(parts) != 3:
            sys.exit(f'{path}:{n}: expected "group | unit | description", got: {line!r}')
        group, unit, desc = parts
        if ' ' in unit:
            sys.exit(f'{path}:{n}: unit {unit!r} must not contain spaces')
        out.append({'group': group, 'unit': unit, 'desc': desc})
    # sanity: no duplicates
    seen = {}
    for s in out:
        if s['unit'] in seen:
            sys.exit(f"{path}: duplicate unit {s['unit']!r}")
        seen[s['unit']] = s
    return out

def units(services, group=None):
    rows = [s for s in services if group in (None, s['group'])]
    return [s['unit'] for s in rows]

def mask_loop(services, group=None):
    return 'for s in ' + ' '.join(units(services, group)) + '; do systemctl mask --runtime --now $s; done'

# --------------------------------------------------------------- sync pieces

def gen_example_toml(services):
    loop = mask_loop(services)
    return f'''version = 1
# sdb path: set for your host. (Example value for this setup.)
sdb = "C:/Users/decog/s90d-root/tools/tizen-sdb/sdb.exe"

# S90D sdbd clogs if injections retry while a /dev/tcp callback is still
# hanging (~2 min). Keep these slower than the default 1/2/5/10/20s.
[retry]
delays = [30.0, 60.0, 90.0, 120.0]

# NOTE: post_root_commands below is GENERATED from config/debloat.services
# by scripts/debloat.py sync — do not edit by hand; edit the services file.
[televisions.s90d]
model = "archive"
host = "192.168.50.36"  # example; real value lives in the gitignored config/
root_on_presence = true
disable_native_execution_policy = false
# Re-applied after every successful root acquisition (TV reboot / new lease).
# Volatile /run masks only — a reboot returns the TV to stock.
# The unit list comes from config/debloat.services.
post_root_commands = [
  "{loop}",
]

[televisions.s90d.remote]
enabled = false
devices = []
rules = []

[televisions.s90d.events]
enabled = false
hdmi_receiver = false
'''

def gen_mask_bat(services):
    loop = mask_loop(services)
    return (
        '@echo off\r\n'
        'rem Idempotent volatile-mask session: re-applies /run systemd masks if absent.\r\n'
        'rem Safe to run any time; a TV reboot clears /run, the next run re-applies.\r\n'
        'rem GENERATED from config/debloat.services by scripts/debloat.py sync.\r\n'
        'chcp 65001 >nul\r\n'
        'set "PYTHONUTF8=1"\r\n'
        'set "PYTHONIOENCODING=utf-8"\r\n'
        'set "PATH=%PATH%;C:\\Program Files\\Git\\usr\\bin"\r\n'
        f'C:\\Users\\decog\\s90d-root\\tools\\samsung-tv-root\\samsung-tv-root-0.0.12-windows-x86_64\\samsung-tv-root.exe --sdb C:\\Users\\decog\\s90d-root\\tools\\tizen-sdb\\sdb.exe archive-root root 192.168.50.36 --command-timeout 150 --command "if [ -L /run/systemd/system/adagent-service.service ]; then echo masks-present; else {loop}; echo REAPPLIED; fi; free | head -2"\r\n'
    )

def gen_readme_table(services):
    lines = [
        '| Group | Unit | What it does |',
        '| --- | --- | --- |',
    ]
    for s in services:
        lines.append(f"| `{s['group']}` | `{s['unit']}` | {s['desc']} |")
    return '\n'.join(lines)

def splice(text, marker, body):
    begin, end = f'<!-- {marker}:begin (generated by scripts/debloat.py sync) -->', f'<!-- {marker}:end -->'
    pre, rest = text.split(begin, 1)
    _, post = rest.split(end, 1)
    return pre + begin + '\n' + body + '\n' + end + post

# --------------------------------------------------------------- commands

def cmd_list(services, group=None):
    for s in services:
        if group in (None, s['group']):
            print(f"{s['group']:14} {s['unit']:46} {s['desc']}")
    print(f'\n{len(units(services, group))} service(s)')

def cmd_sync(services, win_config=False):
    # 1) example toml
    ex = os.path.join(ROOT, 'config', 'daemon.example.toml')
    open(ex, 'w', encoding='utf-8').write(gen_example_toml(services))
    print(f'wrote {ex} ({len(services)} units in the mask loop)')
    # 2) standalone mask bat (CRLF)
    bat = os.path.join(ROOT, 'tools', 'windows', 'run-mask-apply.bat')
    open(bat, 'w', encoding='utf-8', newline='').write(gen_mask_bat(services))
    print(f'wrote {bat}')
    # 3) README table
    rd = os.path.join(ROOT, 'README.md')
    text = open(rd, encoding='utf-8').read()
    open(rd, 'w', encoding='utf-8').write(splice(text, 'debloat-table', gen_readme_table(services)))
    print(f'spliced README.md table ({len(services)} rows)')
    # 4) journal count sanity check
    jr = os.path.join(ROOT, 'docs', 'journal.md')
    text = open(jr, encoding='utf-8').read()
    m = re.search(r'\b(\d+) services masked', text)
    if m and int(m.group(1)) != len(services):
        print(f'WARNING: journal says {m.group(1)} services masked, but debloat.services now lists {len(services)} — update docs/journal.md')
    # 5) live Windows config.toml (optional)
    if win_config:
        if not os.path.exists(WIN_CONFIG):
            sys.exit(f'live config not found: {WIN_CONFIG}')
        old = open(WIN_CONFIG, encoding='utf-8').read()
        pat = re.compile(r'post_root_commands = \[\n[^\n]*\n\]', re.M)
        new, n = pat.subn(WIN_POST_ROOT_TMPL.format(units=' '.join(units(services))), old)
        if n != 1:
            sys.exit('live config: could not find exactly one post_root_commands block — not written')
        if new != old:
            open(WIN_CONFIG, 'w', encoding='utf-8').write(new)
            print(f'refreshed {WIN_CONFIG} post_root_commands')
        else:
            print('live config already in sync')

def main():
    args = [a for a in sys.argv[1:] if not a.startswith('--')]
    flags = {a for a in sys.argv[1:] if a.startswith('--')}
    services = parse()
    cmd = args[0] if args else 'sync'
    if cmd == 'list':
        cmd_list(services, args[1] if len(args) > 1 else None)
    elif cmd == 'sync':
        cmd_sync(services, win_config='--win-config' in flags)
    elif cmd == 'mask-loop':
        print(mask_loop(services, args[1] if len(args) > 1 else None))
    else:
        sys.exit(__doc__)

if __name__ == '__main__':
    main()